const pick = (arr) => arr[Math.floor(rng() * arr.length)];
const wpick = (items) => {
  // items: [value, weight][]
  let z = 0;
  for (const [, w] of items) z += w;
  let r = rng() * z;
  for (const [v, w] of items) { r -= w; if (r <= 0) return v; }
  return items[items.length - 1][0];
};

