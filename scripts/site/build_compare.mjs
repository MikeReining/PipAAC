#!/usr/bin/env node
// Build pipaac.org's compare pages from site/compare-data.json.
//   npm run site:compare          write site/public/compare/*.html
//   npm run site:compare -- --check   exit 1 if the pages are out of date
// Header and footer are copied from site/public/index.html, the one owner
// of site chrome.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const pub = join(root, "site", "public");
const data = JSON.parse(readFileSync(join(root, "site", "compare-data.json"), "utf8"));
const index = readFileSync(join(pub, "index.html"), "utf8");

const between = (s, a, b) => s.slice(s.indexOf(a), s.indexOf(b));
const header = between(index, '  <a class="skip"', '  <main id="main">')
  .replace('<a href="/compare/">', '<a href="/compare/" aria-current="page">');
const footer = between(index, '  <div class="sticky-cta"', "</body>");

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const WORDS = ["Not available", "Limited", "Partial", "Strong", "Built in"];
const ball = (q, pip = false) =>
  `<span class="hb${pip ? " pip" : ""}" style="--q:${q}" role="img" aria-label="${WORDS[q]}" title="${WORDS[q]}"></span>`;
const CTA = `<a class="button" id="hero-cta" href="https://app.pipaac.org">Create your child's board — free <span class="arrow" aria-hidden="true">→</span></a>`;

function badge(row) {
  if (row.only) return ' <span class="only">Only in Pip</span>';
  if (row.better) return ' <span class="only better">Done better</span>';
  return "";
}

function cell(row, slug) {
  if (row.text) return `<td class="txt${slug === "pip" ? " pip-col" : ""}">${esc(row.text[slug])}</td>`;
  return `<td${slug === "pip" ? ' class="pip-col"' : ""}>${ball(row.q[slug], slug === "pip")}</td>`;
}

function noteFor(row, page) {
  if (!row.note) return "";
  const n = typeof row.note === "string" ? row.note : row.note[page];
  return n ? `<small>${esc(n)}</small>` : "";
}

function matrix(cols, page) {
  const head = cols
    .map((c) =>
      c.slug === "pip"
        ? `<th scope="col" class="pip-col"><img src="/brand/pip-mark-seated.svg" alt="" width="24" height="24"> Pip</th>`
        : `<th scope="col">${c.slug === "_" ? "" : `<a href="/compare/${c.slug}">${esc(c.short || c.name)}</a>`}</th>`)
    .join("");
  const body = data.groups
    .map((g) => {
      const rows = g.rows
        .map((r) => {
          const note = noteFor(r, page);
          return `
              <tr><th scope="row">${esc(r.label)}${badge(r)}${note}</th>${cols.map((c) => cell(r, c.slug)).join("")}</tr>`;
        })
        .join("");
      return `
              <tr class="group"><th scope="rowgroup" colspan="${cols.length + 1}">${esc(g.name)}</th></tr>${rows}`;
    })
    .join("");
  return `
        <div class="matrix-wrap">
          <table class="matrix">
            <thead><tr><th scope="col"><span class="visually-hidden">Feature</span></th>${head}</tr></thead>
            <tbody>${body}
            </tbody>
          </table>
        </div>
        <ul class="hb-legend" aria-label="What the circles mean">${data.legend
          .map(([q, t]) => `<li>${ball(q)} ${esc(t)}</li>`)
          .join("")}</ul>
        <p class="matrix-note">Our reading of each app's own published features, ${esc(data.checked)}.</p>`;
}

const finalCta = (title, sub) => `
    <section class="section final" aria-labelledby="final-title">
      <div class="wrap narrow center">
        <img loading="lazy" decoding="async" class="final-bird" src="/pip/hopping.webp" alt="" width="180" height="180">
        <h2 id="final-title">${title}</h2>
        <p class="final-sub">${sub}</p>
        <a class="button big" id="final-cta" href="https://app.pipaac.org">Create your child's board — free <span class="arrow" aria-hidden="true">→</span></a>
      </div>
    </section>`;

function page({ title, desc, path, main }) {
  return `<!doctype html>
<!-- Generated by scripts/site/build_compare.mjs from site/compare-data.json. Edit those, not this file. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(desc)}">
  <meta name="theme-color" content="#f6f4ef">
  <link rel="preload" href="/fonts/andika-bold.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="stylesheet" href="/styles.css">
  <link rel="icon" type="image/png" sizes="32x32" href="/brand/favicon-32.png">
  <link rel="apple-touch-icon" href="/brand/icon-180.png">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(desc)}">
  <meta property="og:url" content="https://pipaac.org${path}">
  <meta property="og:type" content="website">
</head>
<body>
${header}  <main id="main">
${main}
  </main>

${footer}</body>
</html>
`;
}

const pages = {};
const pip = { slug: "pip", name: "Pip" };

for (const c of data.competitors) {
  const quote = c.quote
    ? `
    <section class="section ink" aria-labelledby="quote-title">
      <div class="wrap narrow">
        <h2 id="quote-title" class="visually-hidden">In their own words</h2>
        <blockquote class="their-words">
          <p>"${esc(c.quote.text)}"</p>
          <footer>— <a href="${c.quote.url}" rel="noopener">${esc(c.quote.who)}</a></footer>
        </blockquote>
        <p class="kicker amber">${esc(c.quote.answer)}</p>
      </div>
    </section>`
    : "";
  const diffs = c.diff
    .map(([t, b]) => `
          <article class="step-card"><h3>${esc(t)}</h3><p>${esc(b)}</p></article>`)
    .join("");
  const main = `    <section class="hero-simple wrap" aria-labelledby="hero-title">
      <span class="eyebrow"><a href="/compare/">Compare</a> · ${esc(c.name)}</span>
      <h1 id="hero-title">${esc(c.h1)}</h1>
      <p class="sub knock">${esc(c.knock)}</p>
      ${CTA}
    </section>
${quote}
    <section class="section white" aria-labelledby="matrix-title">
      <div class="wrap">
        <h2 id="matrix-title" class="center">Feature by feature.</h2>${matrix([{ slug: c.slug, name: c.name }, pip], c.slug)}
      </div>
    </section>

    <section class="section" aria-labelledby="diff-title">
      <div class="wrap">
        <h2 id="diff-title" class="center narrow">Where Pip is different.</h2>
        <div class="step-grid">${diffs}
        </div>
      </div>
    </section>
${finalCta("Try Pip tonight alongside what you have.", "It's free, so it costs you nothing to see the difference.")}`;
  pages[`compare/${c.slug}.html`] = page({
    title: `${c.h1} | Pip AAC`,
    desc: c.knock,
    path: `/compare/${c.slug}`,
    main,
  });
}

const cards = data.competitors
  .map((c) => `
          <a class="step-card link-card" href="/compare/${c.slug}"><span class="eyebrow">Pip vs ${esc(c.name)}</span><h3>${esc(c.knock)}</h3><span class="text-link">Read the comparison →</span></a>`)
  .join("");
pages["compare/index.html"] = page({
  title: "Pip vs Proloquo, Proloquo2Go, TouchChat, LAMP, TD Snap and CoughDrop | Pip AAC",
  desc: "Feature by feature: how Pip compares to the big AAC apps. Every word free, $49 once for the whole team, and a board built around your child.",
  path: "/compare/",
  main: `    <section class="hero-simple wrap" aria-labelledby="hero-title">
      <span class="eyebrow">Compare</span>
      <h1 id="hero-title">Same app for every child? Or an app for <em>your</em> child?</h1>
      <p class="sub">The big AAC apps were built in the early iPad era, priced like medical devices, and designed around one idea: their board, their way. Here's Pip against all of them, feature by feature.</p>
      ${CTA}
    </section>

    <section class="section white" aria-labelledby="matrix-title">
      <div class="wrap">
        <h2 id="matrix-title" class="center">Pip vs the field.</h2>
        <p class="swipe-hint" aria-hidden="true">Swipe the table to see every app →</p>${matrix([pip, ...data.competitors], "hub")}
      </div>
    </section>

    <section class="section" aria-labelledby="cards-title">
      <div class="wrap">
        <h2 id="cards-title" class="center">Pip, one by one.</h2>
        <div class="step-grid">${cards}
        </div>
        <p class="center cta-row"><a class="text-link" href="/method">Why we built it this way: "Your child is not a template" →</a></p>
      </div>
    </section>
${finalCta("See the difference tonight.", "Pip is free. Try it alongside what you have.")}`,
});

const check = process.argv.includes("--check");
let stale = 0;
mkdirSync(join(pub, "compare"), { recursive: true });
for (const [rel, html] of Object.entries(pages)) {
  const file = join(pub, rel);
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== html) {
      console.error(`stale: site/public/${rel}`);
      stale++;
    }
  } else writeFileSync(file, html);
}
if (check && stale) {
  console.error("Run: npm run site:compare");
  process.exit(1);
}
console.log(check ? "compare pages up to date" : `wrote ${Object.keys(pages).length} compare pages`);
